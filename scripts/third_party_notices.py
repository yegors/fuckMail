#!/usr/bin/env python3
"""Write the license notices for every Rust crate compiled into the shipped binaries.

Packages carry the result next to THIRD_PARTY_NOTICES.md. The list comes from
`cargo metadata`: every non-workspace package reachable from a workspace member
through normal (non-dev, non-build) dependencies on the host platform. Each
crate's own LICENSE/COPYING/NOTICE files are copied verbatim; identical texts
are printed once with the list of crates that use them.
"""
import argparse
import json
import os
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
LICENSE_PREFIXES = ("license", "licence", "copying", "notice", "copyright", "unlicense")


def host_triple(cargo):
    # rustup installs rustc beside cargo; fall back to PATH for system toolchains.
    rustc = Path(cargo).with_name("rustc" + Path(cargo).suffix)
    output = subprocess.run([str(rustc) if rustc.is_file() else "rustc", "-vV"],
                            check=True, capture_output=True, encoding="utf-8").stdout
    return next(line.split(":", 1)[1].strip() for line in output.splitlines() if line.startswith("host:"))


def cargo_metadata(cargo, triple):
    output = subprocess.run(
        [cargo, "metadata", "--format-version", "1", "--locked", "--filter-platform", triple],
        cwd=ROOT, check=True, capture_output=True, encoding="utf-8").stdout
    return json.loads(output)


def shipped_packages(metadata):
    packages = {package["id"]: package for package in metadata["packages"]}
    nodes = {node["id"]: node for node in metadata["resolve"]["nodes"]}
    members = set(metadata["workspace_members"])
    seen, pending = set(), list(members)
    while pending:
        current = pending.pop()
        if current in seen:
            continue
        seen.add(current)
        for dependency in nodes[current]["deps"]:
            if any(kind["kind"] is None for kind in dependency["dep_kinds"]):
                pending.append(dependency["pkg"])
    return sorted((packages[id] for id in seen - members),
                  key=lambda package: (package["name"], package["version"]))


def license_files(package):
    directory = Path(package["manifest_path"]).parent
    files = [path for path in directory.iterdir()
             if path.is_file() and path.name.lower().startswith(LICENSE_PREFIXES)]
    declared = package.get("license_file")
    if declared:
        path = (directory / declared).resolve()
        if path.is_file() and path not in files:
            files.append(path)
    return sorted(files, key=lambda path: path.name.lower())


def render(packages, triple):
    texts = {}  # normalized text -> (verbatim text, [crate labels])
    missing = []
    index = []
    for package in packages:
        label = package["name"] + " " + package["version"]
        index.append((label, package.get("license") or "see license file", package.get("repository") or ""))
        files = license_files(package)
        if not files:
            missing.append(label)
        for path in files:
            text = path.read_text(encoding="utf-8", errors="replace").strip()
            key = " ".join(text.split())
            texts.setdefault(key, (text, []))[1].append(label)

    lines = [
        "Rust crates compiled into fm-engine and fm",
        "=" * 42,
        "",
        f"Generated by scripts/third_party_notices.py from Cargo.lock for {triple}.",
        "",
    ]
    width = max(len(label) for label, _, _ in index)
    for label, license, repository in index:
        lines.append(f"{label.ljust(width)}  {license}  {repository}".rstrip())
    if missing:
        lines += ["", "These crates publish no license file; their SPDX license applies:", ""]
        lines += ["  " + label for label in missing]
    for text, labels in texts.values():
        lines += ["", "-" * 78, "Used by: " + ", ".join(labels), "-" * 78, "", text]
    return "\n".join(lines) + "\n", len(missing)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--cargo", default=os.environ.get("CARGO", "cargo"))
    args = parser.parse_args()
    triple = host_triple(args.cargo)
    packages = shipped_packages(cargo_metadata(args.cargo, triple))
    text, missing = render(packages, triple)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote notices for {len(packages)} crates to {args.output} ({missing} without a license file)")


if __name__ == "__main__":
    try:
        main()
    except (OSError, subprocess.CalledProcessError, KeyError) as error:
        print("ERROR:", error, file=sys.stderr)
        sys.exit(1)
